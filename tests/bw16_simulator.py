SCENARIOS = r'''
WiFiScanResult ap(int id, int channel) {
  WiFiScanResult result{}; result.bssid[0] = id; result.channel = channel; return result;
}
bool check(bool condition, const char* message) {
  if (!condition) std::cerr << message << '\n';
  return condition;
}
int main(int argc, char** argv) {
  if (argc != 2) return 2;
  std::string scenario = argv[1];
  if (scenario == "single_selected") {
    scan_results = {ap(1, 6), ap(2, 1)}; SelectedVector = {1};
    startSingleAttack(); processSingleAttack();
    return !check(sent_bssid == 2 && sent_channel == 1, "Single did not use selected AP/channel");
  }
  if (scenario == "single_multiple_channels") {
    scan_results = {ap(1, 1), ap(2, 6)}; SelectedVector = {0, 1};
    startSingleAttack(); processSingleAttack();
    if (!check(sent_bssid == 1 && sent_channel == 1, "First AP/channel was not used")) return 1;
    for (int i = 0; i < 5; ++i) processSingleAttack();
    return !check(sent_bssid == 2 && sent_channel == 6 && sends == 2, "Second AP/channel was not used");
  }
  if (scenario == "single_stop") {
    scan_results = {ap(1, 1)}; SelectedVector = {0};
    startSingleAttack(); now_ms = 200; button_pressed = true; confirm_stop = true;
    processSingleAttack();
    return !check(!g_deauthState.running && sends == 0, "Single did not stop before sending");
  }
  if (scenario == "auto_selected") {
    scan_results = {ap(1, 6)}; SelectedVector = {0};
    startAutoSingleAttack(); processAutoSingleAttack();
    return !check(sent_bssid == 1 && sent_channel == 6, "AutoSingle did not use selected AP/channel");
  }
  if (scenario == "auto_restart") {
    scan_results = {ap(1, 6), ap(2, 1)}; SelectedVector = {0};
    startAutoSingleAttack(); processAutoSingleAttack(); stopAttack();
    SelectedVector = {1}; startAutoSingleAttack(); processAutoSingleAttack();
    return !check(sent_bssid == 2 && sent_channel == 1, "AutoSingle reused the previous AP after restart");
  }
  if (scenario == "auto_scan_channel") {
    scan_results = {ap(1, 6)}; next_scan = scan_results; SelectedVector = {0};
    startAutoSingleAttack(); processAutoSingleAttack();
    now_ms += SCAN_INTERVAL; processAutoSingleAttack();
    if (!check(sends == 2, "AutoSingle did not transmit twice across the simulated scan")) return 1;
    if (!check(sent_bssid == 1, "AutoSingle used an unexpected BSSID after the simulated scan")) return 1;
    return !check(sent_channel == 6, "AutoSingle did not restore the target channel after the simulated scan");
  }
  std::cerr << "Unknown scenario\n"; return 2;
}
'''


class SingleModeTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.directory = tempfile.TemporaryDirectory(prefix="bw16-simulator-")
        cls.addClassCleanup(cls.directory.cleanup)
        directory = Path(cls.directory.name)
        fixture = directory / "simulator.cpp"
        cls.executable = directory / "simulator"
        fixture.write_text(SIMULATOR + sketch_definitions() + SCENARIOS, encoding="utf-8")
        command = shlex.split(os.environ.get("CXX", "g++"))
        subprocess.run(command + ["-std=c++11", "-Wall", "-Wextra", str(fixture), "-o", str(cls.executable)], check=True)

    def run_scenario(self, scenario):
        result = subprocess.run([str(self.executable), scenario], capture_output=True, text=True, timeout=5)
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_single_selected(self):
        self.run_scenario("single_selected")

    def test_single_multiple_channels(self):
        self.run_scenario("single_multiple_channels")

    def test_single_stop(self):
        self.run_scenario("single_stop")

    def test_auto_selected(self):
        self.run_scenario("auto_selected")

    def test_known_issue_scenarios_run(self):
        for scenario, message in [
            ("auto_restart", "AutoSingle reused the previous AP after restart"),
            ("auto_scan_channel", "AutoSingle did not restore the target channel after the simulated scan"),
        ]:
            with self.subTest(scenario=scenario):
                result = subprocess.run([str(self.executable), scenario], capture_output=True, text=True, timeout=5)
                self.assertIn(result.returncode, (0, 1), result.stderr)
                if result.returncode == 1:
                    self.assertEqual(result.stderr.strip(), message)

    @unittest.expectedFailure
    def test_auto_restart_uses_new_selection(self):
        self.run_scenario("auto_restart")

    @unittest.expectedFailure
    def test_auto_scan_restores_channel(self):
        self.run_scenario("auto_scan_channel")


if __name__ == "__main__":
    unittest.main(verbosity=2)
